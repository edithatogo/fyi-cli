//! Versioned remote-read failures with fixed, private-safe classifications.
//!
//! Source errors are classified by their types, never by response bodies or
//! formatted messages. The legacy text content remains available alongside this
//! structured envelope so existing callers need not interpret new fields.

use super::policy::PolicyError;
use super::telemetry::{RemoteErrorClassification, RemoteErrorKind, RemoteOperation};
use serde::Serialize;

const SOURCE_FAILURE: &str = "remote operation failed; see operator audit telemetry";
const TIMEOUT_FAILURE: &str = "remote operation timed out; see operator audit telemetry";

/// Safe metadata for a remote read failure. No field contains caller input.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub(crate) struct RemoteReadError {
    pub(crate) schema_version: u8,
    pub(crate) kind: RemoteErrorKind,
    pub(crate) operation: &'static str,
    pub(crate) retryable: bool,
    pub(crate) status: Option<u16>,
    pub(crate) safe_message: &'static str,
    /// Generated by the server; absent when rejected before dispatch admission.
    pub(crate) correlation_id: Option<String>,
    #[serde(skip)]
    text_message: &'static str,
}

impl RemoteReadError {
    /// Preserve typed source status and retryability without source error text.
    pub(crate) fn from_source(
        operation: RemoteOperation,
        error: &anyhow::Error,
        correlation_id: Option<String>,
    ) -> Self {
        let classified = RemoteErrorClassification::classify(operation, error);
        Self {
            schema_version: 1,
            kind: classified.kind,
            operation: operation.as_str(),
            retryable: classified.retryable,
            status: classified.status,
            safe_message: classified.safe_message,
            correlation_id,
            // Preserve the prior text envelope for every source failure. An
            // outer MCP timeout has its existing distinct text, below.
            text_message: SOURCE_FAILURE,
        }
    }

    /// Convert operator-policy failure using only the fixed policy vocabulary.
    pub(crate) fn from_policy(
        operation: RemoteOperation,
        error: &PolicyError,
        correlation_id: Option<String>,
    ) -> Self {
        let (kind, message) = match error {
            PolicyError::InvalidConfiguration(_) => (
                RemoteErrorKind::Validation,
                "remote configuration is invalid",
            ),
            PolicyError::Disabled(message) => (
                RemoteErrorKind::Disabled,
                match message.as_str() {
                    "remote instance is not in the explicit allowlist" => {
                        "remote instance is not in the explicit allowlist"
                    }
                    "remote operation deadline has expired" => {
                        "remote operation deadline has expired"
                    }
                    "remote policy state is unavailable" => "remote policy state is unavailable",
                    "remote MCP kill switch is active" => "remote MCP kill switch is active",
                    "remote MCP is in degraded read-only mode" => {
                        "remote MCP is in degraded read-only mode"
                    }
                    "remote MCP circuit breaker is open" => "remote MCP circuit breaker is open",
                    "remote read capability is disabled for instance" => {
                        "remote read capability is disabled for instance"
                    }
                    "remote write capability is disabled for instance" => {
                        "remote write capability is disabled for instance"
                    }
                    _ => "remote operation is disabled by policy",
                },
            ),
            PolicyError::BudgetExceeded(message) => (
                RemoteErrorKind::BudgetExceeded,
                match message.as_str() {
                    "remote response byte budget exhausted" => {
                        "remote response byte budget exhausted"
                    }
                    "remote operation duration budget exhausted" => {
                        "remote operation duration budget exhausted"
                    }
                    "remote instance concurrency budget exhausted" => {
                        "remote instance concurrency budget exhausted"
                    }
                    _ => "remote instance budget exhausted",
                },
            ),
        };
        Self {
            schema_version: 1,
            kind,
            operation: operation.as_str(),
            retryable: false,
            status: None,
            safe_message: message,
            correlation_id,
            text_message: message,
        }
    }

    /// A wall-clock timeout around the complete admitted MCP operation.
    pub(crate) fn timeout(operation: RemoteOperation, correlation_id: Option<String>) -> Self {
        Self {
            schema_version: 1,
            kind: RemoteErrorKind::Timeout,
            operation: operation.as_str(),
            retryable: operation.is_read(),
            status: None,
            safe_message: "remote operation timed out",
            correlation_id,
            text_message: TIMEOUT_FAILURE,
        }
    }

    /// Reject validated-tool input before dispatch, without retaining its value.
    pub(crate) fn validation(operation: RemoteOperation, safe_message: &'static str) -> Self {
        Self {
            schema_version: 1,
            kind: RemoteErrorKind::Validation,
            operation: operation.as_str(),
            retryable: false,
            status: None,
            safe_message,
            correlation_id: None,
            text_message: safe_message,
        }
    }

    /// Fail closed when local preparation or accounting cannot be completed.
    pub(crate) fn internal(operation: RemoteOperation, correlation_id: Option<String>) -> Self {
        Self {
            schema_version: 1,
            kind: RemoteErrorKind::UpstreamUnknown,
            operation: operation.as_str(),
            retryable: false,
            status: None,
            safe_message: "remote operation could not be completed",
            correlation_id,
            text_message: SOURCE_FAILURE,
        }
    }

    /// Direct internal callers may supply an unknown name; never reflect it.
    pub(crate) fn unknown_operation() -> Self {
        Self {
            schema_version: 1,
            kind: RemoteErrorKind::Validation,
            operation: "unknown",
            retryable: false,
            status: None,
            safe_message: "unsupported remote read operation",
            correlation_id: None,
            text_message: "unsupported remote read operation",
        }
    }
}

impl std::fmt::Display for RemoteReadError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.text_message)
    }
}

impl std::error::Error for RemoteReadError {}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn source_envelope_has_stable_fields_and_never_contains_error_context() {
        let source = anyhow::Error::new(fyi_core::sync::SourceHttpError::new(429))
            .context("synthetic-private-token https://private.example/request/401");
        let failure = RemoteReadError::from_source(
            RemoteOperation::PlanAuthorityFeed,
            &source,
            Some("mcp-7".into()),
        );
        assert_eq!(
            serde_json::to_value(&failure).unwrap(),
            json!({
                "schema_version": 1,
                "kind": "rate_limited",
                "operation": "remote_plan_authority_feed",
                "retryable": true,
                "status": 429,
                "safe_message": "remote endpoint rate limited request",
                "correlation_id": "mcp-7"
            })
        );
        assert_eq!(failure.to_string(), SOURCE_FAILURE);
        assert!(!format!("{failure:?}").contains("synthetic-private"));
        assert!(!serde_json::to_string(&failure)
            .unwrap()
            .contains("private.example"));
    }

    #[test]
    fn unknown_source_messages_cannot_classify_status_or_retryability() {
        let source = anyhow::anyhow!("synthetic-private HTTP 503 timeout 401");
        let failure = RemoteReadError::from_source(RemoteOperation::Health, &source, None);
        assert_eq!(failure.kind, RemoteErrorKind::UpstreamUnknown);
        assert!(!failure.retryable);
        assert_eq!(failure.status, None);
        assert_eq!(failure.correlation_id, None);
    }

    #[test]
    fn nonstandard_http_status_is_retained_without_retry_or_context_disclosure() {
        let source = anyhow::Error::new(fyi_core::sync::SourceHttpError::new(700))
            .context("synthetic-private-custom-status-body HTTP 503");
        let failure = RemoteReadError::from_source(
            RemoteOperation::PlanAuthorityFeed,
            &source,
            Some("mcp-17".into()),
        );
        assert_eq!(failure.kind, RemoteErrorKind::UpstreamUnknown);
        assert_eq!(failure.status, Some(700));
        assert!(!failure.retryable);
        assert_eq!(failure.safe_message, "remote operation failed");
        let mut envelope = json!({"error": failure});
        assert_eq!(
            crate::arguments::validate_arguments(
                &crate::remote_reads::error_schema("remote_plan_authority_feed"),
                &mut envelope,
            ),
            Ok(())
        );
        assert!(!envelope.to_string().contains("synthetic-private"));
    }

    #[test]
    fn policy_envelopes_keep_fixed_reasons_but_redact_unrecognised_messages() {
        for (policy, expected_kind, expected_message) in [
            (
                PolicyError::Disabled("remote read capability is disabled for instance".into()),
                RemoteErrorKind::Disabled,
                "remote read capability is disabled for instance",
            ),
            (
                PolicyError::Disabled("synthetic-private-operator-path".into()),
                RemoteErrorKind::Disabled,
                "remote operation is disabled by policy",
            ),
            (
                PolicyError::BudgetExceeded("remote response byte budget exhausted".into()),
                RemoteErrorKind::BudgetExceeded,
                "remote response byte budget exhausted",
            ),
            (
                PolicyError::BudgetExceeded("synthetic-private-operator-path".into()),
                RemoteErrorKind::BudgetExceeded,
                "remote instance budget exhausted",
            ),
            (
                PolicyError::InvalidConfiguration("synthetic-private-operator-path".into()),
                RemoteErrorKind::Validation,
                "remote configuration is invalid",
            ),
        ] {
            let failure = RemoteReadError::from_policy(RemoteOperation::Version, &policy, None);
            assert_eq!(failure.kind, expected_kind);
            assert_eq!(failure.safe_message, expected_message);
            assert_eq!(failure.to_string(), expected_message);
            assert!(!failure.retryable);
            assert_eq!(failure.correlation_id, None);
            assert_eq!(failure.status, None);
            assert!(!serde_json::to_string(&failure)
                .unwrap()
                .contains("synthetic-private"));
        }
    }

    #[test]
    fn timeout_retryability_is_read_only_and_validation_has_no_correlation() {
        for operation in [
            RemoteOperation::Health,
            RemoteOperation::Version,
            RemoteOperation::SearchRequests,
            RemoteOperation::GetRequest,
            RemoteOperation::ListAuthorities,
            RemoteOperation::DiscoverAuthorityFeeds,
            RemoteOperation::PlanAuthorityFeed,
        ] {
            let failure = RemoteReadError::timeout(operation, Some("mcp-8".into()));
            assert_eq!(failure.kind, RemoteErrorKind::Timeout);
            assert!(failure.retryable);
            assert_eq!(failure.operation, operation.as_str());
            assert_eq!(failure.to_string(), TIMEOUT_FAILURE);
        }
        for operation in [
            RemoteOperation::CreateRequest,
            RemoteOperation::AddCorrespondence,
            RemoteOperation::UpdateState,
        ] {
            assert!(!RemoteReadError::timeout(operation, None).retryable);
        }
        let validation = RemoteReadError::validation(
            RemoteOperation::GetRequest,
            "request_id must be a positive integer",
        );
        assert_eq!(validation.kind, RemoteErrorKind::Validation);
        assert_eq!(validation.correlation_id, None);
        assert!(!validation.retryable);
        assert_eq!(
            validation.to_string(),
            "request_id must be a positive integer"
        );
        let unknown = RemoteReadError::unknown_operation();
        assert_eq!(unknown.operation, "unknown");
        assert_eq!(unknown.status, None);
        let internal = RemoteReadError::internal(RemoteOperation::Health, Some("mcp-9".into()));
        assert_eq!(internal.correlation_id.as_deref(), Some("mcp-9"));
        assert!(!internal.retryable);
        assert_eq!(internal.to_string(), SOURCE_FAILURE);
    }
}
